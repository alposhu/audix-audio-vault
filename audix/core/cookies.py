"""Bridge the embedded browser's session to the yt-dlp backend.

``QWebEngineView`` keeps its cookies inside a ``QWebEngineProfile``; yt-dlp wants a
Netscape-format cookie file. :class:`CookieBridge` subscribes to the profile's
cookie store, mirrors it in memory, and writes ``~/.audix/cookies.txt`` on demand.

The result is that whatever the user can see while signed in inside the app -- an
age-restricted video, a members-only upload -- the downloader can also fetch.

Qt is imported lazily so this module stays importable in headless contexts.
"""
from __future__ import annotations

import logging
import os
import stat
import threading
from pathlib import Path
from typing import Dict, Optional, Tuple

from audix.utils import paths

log = logging.getLogger("audix.cookies")

NETSCAPE_HEADER = (
    "# Netscape HTTP Cookie File\n"
    "# Generated by audix. Do not edit while the application is running.\n"
    "# https://curl.se/docs/http-cookies.html\n"
)

# Only these domains are exported. Nothing else the browser touches is written to
# disk, which keeps unrelated logins out of the cookie file.
ALLOWED_DOMAIN_SUFFIXES = (
    "youtube.com",
    "youtu.be",
    "google.com",
    "googlevideo.com",
    "ytimg.com",
)

# key: (domain, path, name) -> full record
CookieKey = Tuple[str, str, str]


class CookieJar:
    """Thread-safe in-memory cookie store that can serialise to Netscape format."""

    def __init__(self) -> None:
        self._lock = threading.RLock()
        self._cookies: Dict[CookieKey, dict] = {}

    def __len__(self) -> int:
        with self._lock:
            return len(self._cookies)

    def clear(self) -> None:
        with self._lock:
            self._cookies.clear()

    def put(self, domain: str, path: str, name: str, value: str,
            secure: bool, http_only: bool, expires: int) -> None:
        if not _domain_allowed(domain):
            return
        with self._lock:
            self._cookies[(domain, path or "/", name)] = {
                "domain": domain,
                "path": path or "/",
                "name": name,
                "value": value,
                "secure": secure,
                "http_only": http_only,
                "expires": expires,
            }

    def remove(self, domain: str, path: str, name: str) -> None:
        with self._lock:
            self._cookies.pop((domain, path or "/", name), None)

    def to_netscape(self) -> str:
        lines = [NETSCAPE_HEADER]
        with self._lock:
            records = list(self._cookies.values())
        for record in records:
            domain = record["domain"]
            include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
            prefix = "#HttpOnly_" if record["http_only"] else ""
            lines.append(
                "\t".join(
                    [
                        f"{prefix}{domain}",
                        include_subdomains,
                        record["path"],
                        "TRUE" if record["secure"] else "FALSE",
                        str(int(record["expires"])),
                        record["name"],
                        record["value"],
                    ]
                )
            )
        return "\n".join(lines) + "\n"

    def write(self, destination: Optional[Path] = None) -> Optional[Path]:
        """Write the jar to disk with owner-only permissions. Returns the path."""
        if len(self) == 0:
            return None
        target = destination or paths.cookies_file()
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_suffix(".tmp")
        try:
            tmp.write_text(self.to_netscape(), encoding="utf-8")
            os.replace(tmp, target)
            _restrict_permissions(target)
        except OSError as exc:
            log.warning("Could not write cookie file: %s", exc)
            return None
        log.debug("Wrote %d cookies to %s", len(self), target)
        return target


def _domain_allowed(domain: str) -> bool:
    host = domain.lstrip(".").lower()
    return any(host == suffix or host.endswith("." + suffix)
               for suffix in ALLOWED_DOMAIN_SUFFIXES)


def _restrict_permissions(path: Path) -> None:
    """Cookies are credentials; keep them readable only by the owner.

    On POSIX this is a plain 0600. On Windows a new file inherits its parent's
    ACL, which typically also grants Administrators and SYSTEM - so on a shared
    or managed machine another account could read a live YouTube session. The
    inheritance is therefore broken and a single explicit grant applied.
    """
    if os.name == "nt":
        _restrict_windows(path)
        return
    try:
        path.chmod(stat.S_IRUSR | stat.S_IWUSR)
    except OSError:  # pragma: no cover - unusual filesystems
        pass


def _restrict_windows(path: Path) -> None:
    """Break ACL inheritance and grant full control to the current user only."""
    account = os.environ.get("USERNAME") or ""
    domain = os.environ.get("USERDOMAIN") or ""
    principal = f"{domain}\\{account}" if domain and account else account
    if not principal:
        log.warning("Cannot determine the current user; cookie file keeps "
                    "inherited permissions: %s", path)
        return

    from audix.utils.proc import run_capture

    try:
        result = run_capture(
            ["icacls", str(path), "/inheritance:r", "/grant:r", f"{principal}:F"],
            timeout=20,
        )
    except Exception as exc:  # noqa: BLE001 - never block a download on this
        log.warning("Could not restrict cookie file permissions (%s): %s", path, exc)
        return

    if result.returncode == 0:
        log.debug("Cookie file restricted to %s", principal)
    else:
        log.warning(
            "Could not restrict cookie file permissions; it keeps inherited "
            "ACLs. icacls said: %s",
            (result.stdout or result.stderr or "").strip()[:200],
        )


class CookieBridge:
    """Attaches a :class:`CookieJar` to a ``QWebEngineProfile`` cookie store."""

    def __init__(self, profile) -> None:
        self.jar = CookieJar()
        self._profile = profile
        self._store = profile.cookieStore()
        self._store.cookieAdded.connect(self._on_added)
        self._store.cookieRemoved.connect(self._on_removed)
        log.info("Cookie bridge attached to web profile")

    # Qt slots ---------------------------------------------------------------
    def _on_added(self, cookie) -> None:
        try:
            self.jar.put(
                domain=cookie.domain(),
                path=cookie.path(),
                name=bytes(cookie.name()).decode("utf-8", "replace"),
                value=bytes(cookie.value()).decode("utf-8", "replace"),
                secure=cookie.isSecure(),
                http_only=cookie.isHttpOnly(),
                expires=_expiry_epoch(cookie),
            )
        except Exception as exc:  # noqa: BLE001 - never let a slot raise into Qt
            log.debug("Ignoring malformed cookie: %s", exc)

    def _on_removed(self, cookie) -> None:
        try:
            self.jar.remove(
                cookie.domain(),
                cookie.path(),
                bytes(cookie.name()).decode("utf-8", "replace"),
            )
        except Exception as exc:  # noqa: BLE001
            log.debug("Ignoring cookie removal error: %s", exc)

    # public -----------------------------------------------------------------
    def export(self) -> Optional[Path]:
        """Persist the current session cookies for yt-dlp. ``None`` if empty."""
        return self.jar.write()

    def count(self) -> int:
        return len(self.jar)

    def clear_session(self) -> None:
        """Forget every cookie, in the browser profile and on disk."""
        try:
            self._store.deleteAllCookies()
        except Exception as exc:  # noqa: BLE001
            log.debug("deleteAllCookies failed: %s", exc)
        self.jar.clear()
        target = paths.cookies_file()
        try:
            target.unlink(missing_ok=True)
        except OSError:
            pass
        log.info("Cleared browser session cookies")


def _expiry_epoch(cookie) -> int:
    """Session cookies get a far-future expiry so yt-dlp keeps them."""
    expiry = cookie.expirationDate()
    if cookie.isSessionCookie() or not expiry.isValid():
        return 0
    return int(expiry.toSecsSinceEpoch())


def existing_cookie_file() -> Optional[str]:
    """Path to a previously exported cookie file, if one is on disk."""
    path = paths.cookies_file()
    if path.is_file() and path.stat().st_size > len(NETSCAPE_HEADER):
        return str(path)
    return None
